#!/usr/bin/env python3
"""Generates src/sys/nr_*.rs and src/errno.rs from `gcc -dM -E` dumps of the
Linux uapi headers (see `make tables`)."""
import re
import sys
from pathlib import Path

HEADER = "// @generated by tools/gen_tables.py from Linux {ver} uapi headers. Do not edit.\n"


def defines(path, prefix):
    out = {}
    for line in Path(path).read_text().splitlines():
        m = re.fullmatch(r"#define " + prefix + r"(\w+) (\w+)", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def gen_nr(dump, arch, ver):
    nrs = {k: int(v) for k, v in defines(dump, "__NR_").items() if v.isdigit()}
    names = sorted(nrs)
    blob = "".join(names)
    lines = [HEADER.format(ver=ver), f"//! Syscall numbers for {arch}.\n"]
    for n in sorted(names, key=lambda n: nrs[n]):
        lines.append(f"pub const {n.upper()}: usize = {nrs[n]};")
    starts, pos = [], 0
    for n in names:
        starts.append(pos)
        pos += len(n)
    starts.append(pos)
    assert pos < 65536 and max(nrs.values()) < 65536
    lines.append("")
    lines.append("/// Every syscall name, sorted and concatenated; sliced by [`STARTS`].")
    lines.append(f'const NAMES: &str = "{blob}";')
    lines.append("/// Start of each name in [`NAMES`], plus a final end offset.")
    lines.append(f"const STARTS: [u16; {len(starts)}] = {starts};")
    lines.append("/// The number of the syscall at the same index in [`NAMES`].")
    lines.append(f"const NUMBERS: [u16; {len(names)}] = {[nrs[n] for n in names]};")
    lines.append(
        """
/// Looks up a syscall number by its name (e.g. `b"openat"`).
///
/// Returns `None` if this architecture has no such syscall.
pub fn by_name(name: &[u8]) -> Option<usize> {
    let (mut lo, mut hi) = (0, NUMBERS.len());
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let start = *STARTS.get(mid)? as usize;
        let end = *STARTS.get(mid + 1)? as usize;
        let probe = NAMES.as_bytes().get(start..end)?;
        match probe.cmp(name) {
            core::cmp::Ordering::Less => lo = mid + 1,
            core::cmp::Ordering::Greater => hi = mid,
            core::cmp::Ordering::Equal => return NUMBERS.get(mid).map(|&n| n as usize),
        }
    }
    None
}"""
    )
    return "\n".join(lines) + "\n"


def gen_errno(dump, ver):
    raw = defines(dump, "E")
    primary = {k: int(v) for k, v in raw.items() if v.isdigit()}
    aliases = {k: v[1:] for k, v in raw.items() if not v.isdigit()}
    by_num = sorted(primary.items(), key=lambda kv: kv[1])
    out = [HEADER.format(ver=ver)]
    out.append(
        """/// A Linux error number.
#[repr(transparent)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Errno(i32);

impl Errno {"""
    )
    for name, num in by_num:
        out.append(f"    pub const E{name}: Self = Self({num});")
    for name, target in sorted(aliases.items()):
        out.append(f"    pub const E{name}: Self = Self::E{target};")
    out.append(
        """
    #[inline]
    pub const fn from_raw(errno: i32) -> Self {
        Self(errno)
    }

    #[inline]
    pub const fn raw(self) -> i32 {
        self.0
    }

    /// The symbolic name, e.g. `"ENOENT"`, or `None` for an unknown number.
    pub const fn name(self) -> Option<&'static str> {
        Some(match self.0 {"""
    )
    for name, num in by_num:
        out.append(f'            {num} => "E{name}",')
    out.append(
        """            _ => return None,
        })
    }
}"""
    )
    return "\n".join(out) + "\n"


def main():
    src, ver = Path(sys.argv[1]), sys.argv[2]
    root = Path(__file__).resolve().parent.parent
    (root / "src/sys/nr_x86_64.rs").write_text(gen_nr(src / "nr_amd64.txt", "x86_64", ver))
    (root / "src/sys/nr_aarch64.rs").write_text(gen_nr(src / "nr_arm64.txt", "aarch64", ver))
    (root / "src/errno.rs").write_text(gen_errno(src / "errno_amd64.txt", ver))


if __name__ == "__main__":
    main()
